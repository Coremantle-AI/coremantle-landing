// sample any 2d drawing onto the dot grid: the scenes that come from
// glyphs or silhouettes all go through here
const sampleInk = (paint, W, H, step, radius) => {
  const canvas = document.createElement('canvas');
  canvas.width = Math.ceil(W);
  canvas.height = Math.ceil(H);
  const g = canvas.getContext('2d', { willReadFrequently: true });
  g.fillStyle = '#fff';
  paint(g);
  const data = g.getImageData(0, 0, canvas.width, canvas.height).data;
  const pts = [];
  const half = Math.round(step / 2);
  for (let y = half; y < H; y += step) {
    for (let x = half; x < W; x += step) {
      if (data[(y * canvas.width + x) * 4 + 3] > 110) pts.push({ x, y, r: radius });
    }
  }
  return pts;
};

const FONT = '"Noto Sans Devanagari","Space Grotesk",system-ui,sans-serif';
const GREETING = 'नमस्ते';

// WebKit can ignore centered canvas alignment for shaped Devanagari text.
// Position from the measured ink box instead, using left alignment as the
// stable primitive. This also centers glyph overhangs rather than advances.
const paintCenteredText = (g, line, cx, cy, lineOffset, target, cap) => {
  const boxFor = metrics => {
    const hasInkBox = [
      metrics.actualBoundingBoxLeft,
      metrics.actualBoundingBoxRight,
    ].every(Number.isFinite);
    if (!hasInkBox) {
      return {
        left: 0,
        right: metrics.width,
      };
    }
    return {
      left: metrics.actualBoundingBoxLeft,
      right: metrics.actualBoundingBoxRight,
    };
  };

  const probe = 200;
  g.save();
  g.textAlign = 'left';
  g.textBaseline = 'middle';
  g.direction = 'ltr';
  g.font = `700 ${probe}px ${FONT}`;
  const size = Math.min(probe * target / g.measureText(line).width, cap);
  g.font = `700 ${size}px ${FONT}`;
  const box = boxFor(g.measureText(line));
  g.fillText(
    line,
    cx + (box.left - box.right) / 2,
    cy + lineOffset * size * 1.42
  );
  g.restore();
};

// the greeting is always set in Devanagari - never transliterated. Only
// the face waits: the first build uses whatever Devanagari the system
// has, then rebuilds on the Noto subset for a consistent cut.
const words = (W, H, m) => {
  const lines = m ? [GREETING, 'Hello'] : [GREETING + ' ' + 'Hello'];
  // finer than the other scenes: the Devanagari conjunct needs the extra
  // grid rows to stay legible as dots
  const step = m ? 11 : 13;
  return sampleInk(g => {
    const target = W * (m ? 0.86 : 0.78);
    const cap = m ? H * 0.21 : H * 0.32;
    lines.forEach((line, i) => {
      paintCenteredText(
        g,
        line,
        W / 2,
        H / 2,
        i - (lines.length - 1) / 2,
        target,
        cap
      );
    });
  }, W, H, step, step * 0.38);
};

