// [centre, half-width, height] in box units; the skyline is the max of them
const PEAKS = [[0.17, 0.26, 0.40], [0.42, 0.28, 0.72], [0.66, 0.22, 0.50], [0.88, 0.24, 0.42]];
const FORE = [[0.10, 0.38, 0.30], [0.52, 0.34, 0.24], [0.86, 0.28, 0.32]];

const ridgeAt = (peaks, u, floor) => {
  let h = floor;
  for (let i = 0; i < peaks.length; i++) {
    const d = Math.abs(u - peaks[i][0]) / peaks[i][1];
    if (d < 1) h = Math.max(h, peaks[i][2] * (1 - d) * (1 - 0.26 * d));
  }
  return 1 - h;                          // v of the ridge, screen-down
};

const mountain = (W, H, m) => {
  const x0 = W * (m ? 0.05 : 0.12), x1 = W * (m ? 0.95 : 0.88);
  const y0 = H * (m ? 0.26 : 0.17), y1 = H * (m ? 0.74 : 0.88);
  const step = m ? 14 : 17;
  const bw = x1 - x0, bh = y1 - y0;

  const skyline = u => ridgeAt(PEAKS, u, 0.14);
  // a nearer ridge crossing the frame: its crest is the dark diagonal that
  // gives the massif its depth
  const foreline = u => ridgeAt(FORE, u, 0.02);

  // tone, not presence, carries the shading — the massif stays solid and
  // the dot radius does the work, the way a halftone plate does
  const lumAt = (u, v) => {
    const back = skyline(u), fore = foreline(u);
    if (v < back) return 0.13 * Math.pow(v / Math.max(back, 0.01), 2.6);  // haze under the ridge
    const grad = 0.014;
    if (v < fore) {
      // lit from the left: a flank descending to the right takes the light
      const slope = (skyline(u + grad) - skyline(u - grad)) / (2 * grad);
      const t = clamp01((v - back) / Math.max(fore - back, 0.02));
      return 0.24 + 0.48 * clamp01(0.5 + slope * 0.62) + 0.20 * (1 - t * t);
    }
    const slope = (foreline(u + grad) - foreline(u - grad)) / (2 * grad);
    const t = clamp01((v - fore) / Math.max(1 - fore, 0.02));
    // the near ridge sits in its own shadow and falls away toward the frame
    return (0.18 + 0.32 * clamp01(0.5 + slope * 0.62)) * (1 - 0.5 * t);
  };

  const pts = [];
  for (let y = y0; y <= y1; y += step) {
    for (let x = x0; x <= x1; x += step) {
      const lum = lumAt((x - x0) / bw, (y - y0) / bh);
      // only the faintest tones dither away, so the silhouette stays whole
      if (lum <= 0.03 + 0.14 * hash2(x, y)) continue;
      pts.push({ x, y, r: step * (0.09 + 0.30 * clamp01(lum)) });
    }
  }
  return pts;
};

