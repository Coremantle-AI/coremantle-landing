// resample a cloud to exactly n points: denser clouds are thinned on an
// even stride (which preserves the shape), sparser ones are padded with
// invisible clones that grow out of a neighbour in the next scene
const fit = (pts, n) => {
  const len = pts.length;
  if (!len) return [];
  const out = new Array(n);
  if (len >= n) {
    for (let i = 0; i < n; i++) {
      const p = pts[Math.floor(i * len / n)];
      out[i] = { x: p.x, y: p.y, r: p.r, a: p.a == null ? 1 : p.a };
    }
  } else {
    for (let i = 0; i < len; i++) {
      const p = pts[i];
      out[i] = { x: p.x, y: p.y, r: p.r, a: p.a == null ? 1 : p.a };
    }
    for (let i = len; i < n; i++) {
      const p = pts[(i * 7919) % len];
      out[i] = { x: p.x, y: p.y, r: 0, a: 0 };
    }
  }
  return out;
};

