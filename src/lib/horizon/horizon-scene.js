// "Speech is only the beginning": one dot field, four scenes. A speech
// waveform assembles, resolves into words, the words recompose into a
// landscape, the landscape into a robot - the modalities the data layer
// expands into.
//
// Every scene is the SAME N points reassigned, so each transition is a real
// morph rather than a crossfade: point i is sorted by x in every cloud, so
// the field recomposes left-to-right instead of scrambling. Scroll drives a
// single --hp (0 -> 1) on the card; the canvas reads it per frame and the
// HUD chrome reads it through the --s/--v clamp idiom (styles:
// styles/components/horizon.css).
//
// Ported from the static site's horizon.js. The scene geometry and painting
// are unchanged; mounting is now explicit (`mountHorizon(card)`, called by
// components/horizon/HorizonCard) and returns a cleanup for route changes.

const clamp01 = v => (v < 0 ? 0 : v > 1 ? 1 : v);
const lerp = (a, b, t) => a + (b - a) * t;
const easeInOut = t => (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2);
// deterministic value noise: every reload composes the identical frame, so
// the scrub is reproducible (and the dither never crawls between renders)
const hash = i => {
  const h = Math.sin(i * 127.1 + 311.7) * 43758.5453;
  return h - Math.floor(h);
};
const hash2 = (x, y) => {
  const h = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453;
  return h - Math.floor(h);
};


/* ------------------------------------------------------------------ *
 * scene 1 — the speech waveform                                       *
 * ------------------------------------------------------------------ */

// syllables as [centre, width, height]: a plausible utterance envelope
// (two loud clusters mid-phrase, trailing off at both ends)
const SYL = [
  [0.10, 0.024, 0.26], [0.15, 0.020, 0.44], [0.20, 0.026, 0.33],
  [0.27, 0.022, 0.62], [0.32, 0.018, 0.41], [0.37, 0.024, 0.78],
  [0.43, 0.020, 0.52], [0.48, 0.026, 0.95], [0.54, 0.019, 0.58],
  [0.59, 0.023, 0.83], [0.65, 0.020, 0.47], [0.71, 0.025, 0.66],
  [0.77, 0.019, 0.36], [0.83, 0.023, 0.44], [0.89, 0.020, 0.22],
];
const waveEnv = u => {
  let v = 0;
  for (let i = 0; i < SYL.length; i++) {
    const d = (u - SYL[i][0]) / SYL[i][1];
    if (d > -3.2 && d < 3.2) v += SYL[i][2] * Math.exp(-d * d);
  }
  // fine grain so neighbouring columns don't read as one smooth blob
  return v * (0.84 + 0.16 * Math.sin(u * 197));
};

const waveform = (W, H, m) => {
  const pts = [];
  const cy = H * 0.5;
  const step = m ? 17 : 21;
  const x0 = W * 0.05, x1 = W * 0.95;
  const cols = Math.round((x1 - x0) / step);
  const amp = H * (m ? 0.26 : 0.40);
  for (let c = 0; c <= cols; c++) {
    const x = x0 + c * step;
    const rows = Math.round(waveEnv(c / cols) * amp / step);
    pts.push({ x, y: cy, r: step * 0.21 });     // the spine runs edge to edge
    for (let j = 1; j <= rows; j++) {
      const f = 1 - j / (rows + 1);             // taper the tips
      const r = step * (0.14 + 0.075 * f);
      pts.push({ x, y: cy - j * step, r });
      pts.push({ x, y: cy + j * step, r });
    }
  }
  return pts;
};

