/**
 * Builds the horizon stage inside `card` (an empty `[data-horizon]` element)
 * and scrubs it with scroll.
 * @returns {() => void} cleanup
 */
export function mountHorizon(card) {
  const cards = new Set();
  const reduced = matchMedia('(prefers-reduced-motion: reduce)');
  let frame = 0;
  let disposed = false;

  const paint = card => {
    const state = card._hz;
    if (!state || !state.clouds) return;
    const { ctx, clouds, W, H } = state;
    const p = state.p;

    let k = 0, t = 1;
    for (let i = 0; i < MORPHS.length; i++) {
      if (p >= MORPHS[i][0]) {
        k = i;
        t = clamp01((p - MORPHS[i][0]) / (MORPHS[i][1] - MORPHS[i][0]));
      }
    }
    const A = clouds[k], B = clouds[k + 1];
    const n = A.length;
    // the waveform keeps breathing through its dwell so the scene isn't dead
    // while the reader sits on it — still scroll-driven, never on a clock.
    // It tapers to nothing before the next morph, or the field would snap
    // back to the composed cloud the morph reads from.
    const holding = k === 0 && t > 0.995;
    const live = holding ? clamp01((MORPHS[1][0] - p) / 0.06) : 0;

    ctx.clearRect(0, 0, W, H);
    // one path per alpha bucket: 1450 dots become 8 fills instead of 1450
    const buckets = state.buckets;
    for (let i = 0; i < buckets.length; i++) buckets[i].length = 0;

    for (let i = 0; i < n; i++) {
      const a = A[i], b = B[i];
      // stagger by index — the clouds are x-sorted, so the morph sweeps
      // across the field instead of every dot leaving at once
      const ti = easeInOut(clamp01((t - (i / n) * SWEEP) / (1 - SWEEP)));
      let x = lerp(a.x, b.x, ti), y = lerp(a.y, b.y, ti);
      const alpha = lerp(a.a, b.a, ti);
      let r = lerp(a.r, b.r, ti);

      if (ti > 0 && ti < 1) {
        const dx = b.x - a.x, dy = b.y - a.y;
        const d = Math.hypot(dx, dy);
        if (d > 1) {
          // bow the path sideways and let the dot shrink in flight, so the
          // field looks like it's travelling rather than cross-dissolving
          const arc = Math.sin(Math.PI * ti) * Math.min(70, d * 0.16) * (hash(i) < 0.5 ? -1 : 1);
          x += (-dy / d) * arc;
          y += (dx / d) * arc;
          const s = Math.sin(Math.PI * ti);
          x += (hash(i + 1) - 0.5) * 26 * s;
          y += (hash(i + 2) - 0.5) * 26 * s;
          r *= 1 - 0.34 * s;
        }
      } else if (live) {
        // amplitude scales with the column's own height, so the spine stays
        // put and the tall spikes move most
        y += Math.sin(p * 26 + b.x * 0.012) * Math.abs(b.y - H * 0.5) * 0.05 * live;
      }

      if (r < 0.4 || alpha < 0.04) continue;
      const bucket = buckets[Math.min(7, (alpha * 7.99) | 0)];
      bucket.push(x, y, r);
    }

    ctx.fillStyle = state.ink;
    for (let i = 0; i < buckets.length; i++) {
      const bucket = buckets[i];
      if (!bucket.length) continue;
      ctx.globalAlpha = (i + 1) / 8;
      ctx.beginPath();
      for (let j = 0; j < bucket.length; j += 3) {
        ctx.moveTo(bucket[j] + bucket[j + 2], bucket[j + 1]);
        ctx.arc(bucket[j], bucket[j + 1], bucket[j + 2], 0, 6.283185);
      }
      ctx.fill();
    }
    ctx.globalAlpha = 1;
  };

  const measure = card => {
    const state = card._hz;
    const stage = state.stage;
    const cssW = stage.clientWidth, cssH = stage.clientHeight;
    if (!cssW || !cssH) return false;
    const m = cssH > cssW;
    const W = m ? 900 : 1600, H = m ? 1150 : 900;
    const changed = state.W !== W || state.H !== H;
    const dpr = Math.min(devicePixelRatio || 1, 2);
    state.canvas.width = Math.round(cssW * dpr);
    state.canvas.height = Math.round(cssH * dpr);
    state.ctx.setTransform(cssW * dpr / W, 0, 0, cssH * dpr / H, 0, 0);
    state.W = W; state.H = H;
    if (changed || !state.clouds) {
      state.clouds = buildClouds(W, H, m);
      state.hud.outerHTML = svgMarkup(W, H, m);
      state.hud = stage.querySelector('.hz-hud');
    }
    return true;
  };

  const readInk = card => {
    card._hz.ink = getComputedStyle(card).color || '#f6f4ef';
  };

  const seek = () => {
    frame = 0;
    cards.forEach(card => {
      const state = card._hz;
      if (!state) return;
      let p = 1;
      if (!reduced.matches) {
        const track = card.closest('.hz-track');
        // a collapsed track means the card is not pinned (mobile, reduced motion)
        const dist = track ? track.offsetHeight - innerHeight : 0;
        const pinned = dist > 200;
        const rect = (pinned ? track : card).getBoundingClientRect();
        if (rect.bottom < -200 || rect.top > innerHeight + 200) return;
        if (pinned) {
          p = clamp01(-rect.top / dist);
        } else {
          // unpinned fallback: hold the first frame until most of the card is
          // on screen, then scrub through the fully-visible zone
          const end = innerHeight * 0.22;
          const start = Math.max(end + 120, Math.min(innerHeight * 0.92, innerHeight - rect.height * 0.72));
          p = clamp01((start - rect.top) / (start - end));
        }
      }
      if (!state.clouds && !measure(card)) return;
      if (p === state.p && state.painted) return;
      state.p = p;
      state.painted = true;
      card.style.setProperty('--hp', p.toFixed(4));
      paint(card);
    });
  };

  const schedule = () => { if (!frame) frame = requestAnimationFrame(seek); };

  // throw the point clouds away and re-derive them: the only thing that
  // invalidates the geometry itself is a new font arriving
  const rebuild = () => {
    cards.forEach(card => {
      const state = card._hz;
      if (!state) return;
      state.clouds = null;
      state.painted = false;
      measure(card);
    });
    schedule();
  };

  // until the subset face lands the greeting is set in whatever Devanagari
  // the system has, then rebuilt on Noto for a consistent cut
  const probeFont = () => {
    if (notoLoaded || !document.fonts) return;
    const check = () => document.fonts.load(`700 200px "Noto Sans Devanagari"`, GREETING)
      .then(faces => {
        if (!faces.length || notoLoaded) return;
        notoLoaded = true;
        if (!disposed) rebuild();
      })
      .catch(() => {});
    check();
    document.fonts.ready.then(check).catch(() => {});
  };

  const resize = new ResizeObserver(() => {
    cards.forEach(card => {
      if (!card._hz) return;
      card._hz.painted = false;
      measure(card);
    });
    schedule();
  });

  ensureFontSubset();
  probeFont();
  const stage = document.createElement('div');
  const canvas = document.createElement('canvas');
  stage.className = 'hz-stage';
  canvas.className = 'hz-canvas';
  stage.appendChild(canvas);
  stage.insertAdjacentHTML('beforeend', svgMarkup(1600, 900, false));
  card.appendChild(stage);
  card._hz = {
    stage, canvas, hud: stage.querySelector('.hz-hud'),
    ctx: canvas.getContext('2d'), p: -1, painted: false,
    buckets: Array.from({ length: 8 }, () => []),
  };
  readInk(card);
  measure(card);
  cards.add(card);
  resize.observe(stage);

  const onMotionChange = () => {
    cards.forEach(card => { if (card._hz) card._hz.painted = false; });
    schedule();
  };
  // the theme toggle swaps the ink colour the canvas draws with, which lives
  // outside CSS - so the field has to be repainted, not just restyled
  const themeObserver = new MutationObserver(() => {
    cards.forEach(card => {
      if (!card._hz) return;
      readInk(card);
      card._hz.painted = false;
    });
    schedule();
  });

  addEventListener('scroll', schedule, { passive: true });
  addEventListener('resize', schedule);
  addEventListener('pageshow', schedule);
  reduced.addEventListener('change', onMotionChange);
  themeObserver.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
  schedule();

  return () => {
    disposed = true;
    removeEventListener('scroll', schedule);
    removeEventListener('resize', schedule);
    removeEventListener('pageshow', schedule);
    reduced.removeEventListener('change', onMotionChange);
    themeObserver.disconnect();
    resize.disconnect();
    if (frame) cancelAnimationFrame(frame);
    cards.clear();
    stage.remove();
    delete card._hz;
  };
}
